const BN_DIGITS = '০১২৩৪৫৬৭৮৯';

export function num(n: number): string {
  const s = String(n);
  return settings.lang === 'bn' ? s.replace(/\d/g, (d) => BN_DIGITS[Number(d)]!) : s;
}

export function t(key: Key | (string & {}), params?: Record<string, string | number>): string {
  const raw = (settings.lang === 'bn' ? bn[key as Key] : undefined) ?? en[key as Key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = params[k];
    return v === undefined ? `{${k}}` : typeof v === 'number' ? num(v) : v;
  });
}

